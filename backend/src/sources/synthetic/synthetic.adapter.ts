import type { EventFetchResult, EventSourceAdapter, NormalizedEvent, TimeWindow } from "../source-adapter.js";

export const SYNTHETIC_SOURCE_ID = "demo-seismic-synthetic";
const EVENT_COUNT = 40;

/**
 * Offline demo source. Every event is generated, labeled synthetic, and never presented as INGV data.
 * Events are deterministic for a given window so repeated imports are reproducible.
 */
export function createSyntheticAdapter(): EventSourceAdapter {
  return {
    descriptor: {
      id: SYNTHETIC_SOURCE_ID,
      label: "Synthetic seismic events (offline demo, not real data)",
      mode: "synthetic_local",
      license: "CC0-1.0",
      attribution: "Generated by WaypointAI for demonstration; not observed data",
      sourceUrl: null,
    },
    async fetchEvents(window: TimeWindow): Promise<EventFetchResult> {
      return { events: generateSyntheticEvents(window), skipped: 0, truncated: false };
    },
  };
}

export function generateSyntheticEvents(window: TimeWindow): NormalizedEvent[] {
  const random = mulberry32(20261013);
  const span = Math.max(0, window.end.getTime() - window.start.getTime());
  return Array.from({ length: EVENT_COUNT }, (_, index) => {
    const observedAt = new Date(window.end.getTime() - Math.round(span * (index + random()) / EVENT_COUNT));
    const magnitude = Math.round((0.5 + random() * 3.5) * 10) / 10;
    const depthKm = Math.round(random() * 300) / 10;
    // Central Apennines, where the imported OSM extract has places to link to.
    const lat = Math.round((41.6 + random() * 1.8) * 10_000) / 10_000;
    const lon = Math.round((12.4 + random() * 1.6) * 10_000) / 10_000;
    const number = String(index + 1).padStart(3, "0");
    return {
      externalId: `synthetic-${number}`,
      observedAt,
      lat,
      lon,
      category: "seismic:earthquake",
      revision: observedAt.toISOString(),
      attributes: {
        label: `M${magnitude} · Synthetic demo event ${number}`,
        magnitude,
        magnitudeType: "ML",
        depthKm,
        placeDescription: `Synthetic demo event ${number}`,
        author: "synthetic",
        sourceEventUrl: null,
      },
    };
  }).filter((event) => event.observedAt >= window.start && event.observedAt <= window.end);
}

function mulberry32(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4_294_967_296;
  };
}
